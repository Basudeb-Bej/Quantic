const mongoose = require("mongoose");

const chatSchema = new mongoose.Schema(
	{
		userId: {
			type: mongoose.Schema.Types.ObjectId,
			ref: "User",
			required: true,
			index: true,
		},
		title: {
			type: String,
			default: "New Chat",
			trim: true,
		},
		lastMessage: {
			type: String,
			default: "",
			trim: true,
		},
		preview: {
			type: String,
			default: "",
			trim: true,
		},
		pinned: {
			type: Boolean,
			default: false,
		},
		archived: {
			type: Boolean,
			default: false,
		},
		titleAutoGenerated: {
			type: Boolean,
			default: true
		},
		lastMessageAt: {
			type: Date,
			default: Date.now,
			index: true,
		},
	},
	{
		timestamps: true,
		collection: "chathistorys",
	}
);

chatSchema.index({ userId: 1, lastMessageAt: -1 });
chatSchema.index({ userId: 1, archived: 1 });

module.exports = mongoose.model("Chat", chatSchema);